export type ExperimentalPredictionsResponse = {
  status: "experimental";
  capture_running: boolean;
  live_feature_equivalence_verified: boolean;
  alerts_enabled: boolean;
  active_flow_count: number;
  prediction_count: number;
  predictions: ExperimentalFlowPrediction[];
};

// ============================================================
// Signature-Based Detection and Threat Scoring Types
// ============================================================

export type ThreatClassification =
  | "normal"
  | "low"
  | "medium"
  | "high";

export type DetectionMethod =
  | "signature"
  | "ml"
  | "combined";

/**
 * Signature-based security alert generated by FlowBridge.
 *
 * Existing fields are produced by PortScanTracker and
 * the live capture detection pipeline.
 *
 * Sprint 5 adds:
 * - threat_score
 * - classification
 * - detection_method
 */
export type SignatureAlert = {
  // Signature detection results
  detected: boolean;
  attack_type: string | null;
  severity: ThreatClassification;
  reason: string;
  rule_id: string;

  // Network information
  source_ip: string;
  destination_ip: string;
  ports_scanned: number;

  // Alert metadata
  timestamp: string;
  event_type: string;
  status: string;

  // Sprint 5: Threat Scoring and Classification
  threat_score?: number;
  classification?: ThreatClassification;
  detection_method?: DetectionMethod;
};

/**
 * Response returned by:
 *
 * GET /capture/alerts
 *
 * Alerts are generated by the backend and returned
 * newest first.
 */
export type SignatureAlertsResponse = {
  status: string;
  capture_running: boolean;
  alert_count: number;
  alerts: SignatureAlert[];
};

// ============================================================
// API Request Helper
// ============================================================

async function apiRequest<T>(
  path: string,
  options?: RequestInit,
): Promise<T> {
  const response = await fetch(`${API_URL}${path}`, {
    ...options,
    credentials: "include",
  });

  if (!response.ok) {
    // Notify the application if the authenticated
    // session has expired.
    if (response.status === 401) {
      reportSessionExpiry();
    }

    // Experimental predictions may not be available
    // on every backend configuration.
    if (
      response.status === 404 &&
      path === "/capture/experimental-predictions"
    ) {
      throw new Error(
        "Experimental AI predictions are unavailable on this backend (HTTP 404). The backend/ML integration is still pending.",
      );
    }

    // Do not replace missing signature alerts with
    // mock or fabricated security events.
    if (
      response.status === 404 &&
      path === "/capture/alerts"
    ) {
      throw new Error(
        "Live signature alerts are unavailable on this backend (HTTP 404).",
      );
    }

    const error = await response.json().catch(() => null);

    throw new Error(
      typeof error?.detail === "string"
        ? error.detail
        : `Request failed: ${response.status}`,
    );
  }

  return response.json() as Promise<T>;
}

// ============================================================
// Capture Service
// ============================================================

export const captureService = {
  // ==========================================================
  // Network Interfaces
  // ==========================================================

  /**
   * Retrieve the available network interfaces.
   */
  async getInterfaces() {
    return apiRequest<{ interfaces: CaptureInterface[] }>(
      "/capture/interfaces",
    );
  },

  // ==========================================================
  // Packet Capture Status and Statistics
  // ==========================================================

  /**
   * Retrieve current network capture status.
   */
  async getStatus() {
    return apiRequest<CaptureStatus>(
      "/capture/status",
    );
  },

  /**
   * Retrieve live network capture statistics.
   */
  async getStats() {
    return apiRequest<CaptureStats>(
      "/capture/stats",
    );
  },

  /**
   * Start packet capture on the selected interface.
   */
  async start(interfaceName: string) {
    return apiRequest("/capture/start", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        interface: interfaceName,
      }),
    });
  },

  /**
   * Stop the current network capture session.
   */
  async stop() {
    return apiRequest("/capture/stop", {
      method: "POST",
    });
  },

  // ==========================================================
  // AEGIS Experimental AI Detection
  // ==========================================================

  /**
   * Retrieve experimental AI predictions for
   * completed TCP/UDP network flows.
   *
   * Backend endpoint:
   * GET /capture/experimental-predictions
   *
   * These predictions are experimental and do
   * not represent confirmed security incidents.
   *
   * The ML attack probability is distinct from
   * the Sprint 5 threat score.
   */
  async getExperimentalPredictions() {
    return apiRequest<ExperimentalPredictionsResponse>(
      "/capture/experimental-predictions",
    );
  },

  // ==========================================================
  // Live Signature-Based Intrusion Detection Alerts
  // ==========================================================

  /**
   * Retrieve real signature-based security alerts.
   *
   * Backend endpoint:
   * GET /capture/alerts
   *
   * Sprint 5 integration:
   * Newly generated alerts include:
   * - threat_score: 0-100
   * - classification: normal/low/medium/high
   * - detection_method: signature
   *
   * Historical or older backend responses may lack
   * the scoring fields, so the frontend types
   * temporarily allow those fields to be absent.
   *
   * This method does not create mock alerts.
   */
  async getSignatureAlerts() {
    return apiRequest<SignatureAlertsResponse>(
      "/capture/alerts",
    );
  },
};
