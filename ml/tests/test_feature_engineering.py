
"""
KAN-126 — TEST-04
Validate Feature Engineering, X/y Split, and Data Leakage.

These integration tests validate the actual model-ready
CICIDS2017 datasets generated by Notebook 10.

Run:
    python -m pytest ml/tests/test_feature_engineering.py -v

The full dataset CSVs are required locally.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest


PROJECT_ROOT = Path(__file__).resolve().parents[2]

DATA_DIR = (
    PROJECT_ROOT
    / "ml"
    / "data"
    / "processed"
    / "model_ready"
)

FEATURES = [
    "Flow Duration",
    "Total Fwd Packets",
    "Total Backward Packets",
    "Flow Bytes/s",
    "Flow Packets/s",
]

TARGET = "BinaryLabel"

METADATA = [
    "Label",
    "SourceDataset",
    "SourceRow",
]

EXPECTED_COLUMNS = FEATURES + [TARGET] + METADATA

SPLITS = ["train", "validation", "test"]

EXPECTED_ROW_COUNTS = {
    "train": 1_791_100,
    "validation": 376_404,
    "test": 405_023,
}

EXPECTED_TOTAL = 2_572_527


# ==================================================
# LOAD DATASETS ONCE
# ==================================================

@pytest.fixture(scope="module")
def datasets():
    """
    Read all three model-ready datasets once.

    Skip full-dataset tests in CI if the large
    generated CSV files are not available.
    """

    paths = {
        name: DATA_DIR / f"CICIDS2017_Binary_{name}.csv"
        for name in SPLITS
    }

    missing = [
        str(path)
        for path in paths.values()
        if not path.is_file()
    ]

    if missing:
        pytest.skip(
            "Full model-ready datasets unavailable: "
            + ", ".join(missing)
        )

    return {
        name: pd.read_csv(path, low_memory=False)
        for name, path in paths.items()
    }


@pytest.fixture(scope="module")
def signatures(datasets):
    """
    Calculate the same five-feature signatures used
    by Notebook 10 for each saved partition.
    """

    return {
        name: set(
            pd.util.hash_pandas_object(
                df[FEATURES],
                index=False,
            ).to_numpy(dtype="uint64")
        )
        for name, df in datasets.items()
    }


# ==================================================
# TEST 1 — ALL THREE SPLITS LOAD
# ==================================================

def test_all_splits_load(datasets):
    assert set(datasets) == set(SPLITS)

    for name, df in datasets.items():
        assert isinstance(df, pd.DataFrame)
        assert not df.empty, f"{name} dataset is empty"


# ==================================================
# TEST 2 — EXPECTED RECORD COUNTS
# ==================================================

def test_split_record_counts(datasets):
    for name, expected in EXPECTED_ROW_COUNTS.items():
        actual = len(datasets[name])

        assert actual == expected, (
            f"{name}: expected {expected}, got {actual}"
        )

    assert sum(len(df) for df in datasets.values()) == EXPECTED_TOTAL


# ==================================================
# TEST 3 — FEATURE SCHEMA CONSISTENCY
# ==================================================

def test_feature_schema_consistency(datasets):
    for name, df in datasets.items():
        assert list(df.columns) == EXPECTED_COLUMNS, (
            f"{name}: unexpected column schema"
        )

        assert df.columns.is_unique


# ==================================================
# TEST 4 — ALL MODEL FEATURES NUMERIC
# ==================================================

def test_numerical_features(datasets):
    for name, df in datasets.items():
        for feature in FEATURES:
            assert pd.api.types.is_numeric_dtype(
                df[feature]
            ), f"{name}: {feature} is not numeric"


# ==================================================
# TEST 5 — NO MISSING OR INFINITE FEATURES
# ==================================================

def test_finite_feature_values(datasets):
    for name, df in datasets.items():
        values = df[FEATURES].to_numpy(
            dtype=np.float64
        )

        assert np.isfinite(values).all(), (
            f"{name}: missing or infinite features"
        )


# ==================================================
# TEST 6 — NO NEGATIVE SELECTED FEATURES
# ==================================================

def test_nonnegative_features(datasets):
    """
    Notebook 10 excludes rows where any
    selected model feature is negative.
    """

    for name, df in datasets.items():
        assert (df[FEATURES] >= 0).all().all(), (
            f"{name}: negative feature values found"
        )


# ==================================================
# TEST 7 — CORRECT BINARY LABEL ENCODING
# ==================================================

def test_binary_target_encoding(datasets):
    for name, df in datasets.items():
        assert set(df[TARGET].unique()) == {0, 1}, (
            f"{name}: expected BENIGN and ATTACK"
        )

        expected = (
            df["Label"] != "BENIGN"
        ).astype(np.int8)

        actual = df[TARGET].astype(np.int8)

        assert np.array_equal(
            actual.to_numpy(),
            expected.to_numpy(),
        ), f"{name}: binary encoding mismatch"


# ==================================================
# TEST 8 — X/y SEPARATION
# ==================================================

def test_xy_separation(datasets):
    """
    Verify that the intended X/y selection uses only
    five model features and the binary target.

    This validates exported-data compatibility.
    Notebook 11 must also be checked to confirm
    actual model training uses this selection.
    """

    prohibited = {
        "BinaryLabel",
        "Label",
        "SourceDataset",
        "SourceRow",
        "FeatureSignature",
        "Split",
    }

    for name, df in datasets.items():
        X = df[FEATURES]
        y = df[TARGET]

        assert X.shape == (len(df), 5)
        assert y.shape == (len(df),)

        assert set(X.columns) == set(FEATURES)
        assert not prohibited.intersection(X.columns)

        assert pd.api.types.is_numeric_dtype(y)


# ==================================================
# TEST 9 — NO OVERLAPPING SOURCE RECORDS
# ==================================================

def test_no_source_record_overlap(datasets):
    """
    A source record must not appear in more than
    one train/validation/test partition.
    """

    seen = set()

    for name in SPLITS:
        df = datasets[name]

        identifiers = set(
            zip(
                df["SourceDataset"],
                df["SourceRow"],
            )
        )

        assert len(identifiers) == len(df), (
            f"{name}: duplicate source identifiers"
        )

        assert seen.isdisjoint(identifiers), (
            f"{name}: source records overlap splits"
        )

        seen.update(identifiers)


# ==================================================
# TEST 10 — NO CROSS-SPLIT FEATURE SIGNATURES
# ==================================================

def test_no_feature_signature_leakage(signatures):
    """
    Identical five-feature signatures must not
    appear in different partitions.
    """

    train = signatures["train"]
    validation = signatures["validation"]
    test = signatures["test"]

    assert train.isdisjoint(validation), (
        "Feature signatures overlap train/validation"
    )

    assert train.isdisjoint(test), (
        "Feature signatures overlap train/test"
    )

    assert validation.isdisjoint(test), (
        "Feature signatures overlap validation/test"
    )


# ==================================================
# TEST 11 — CLASS COVERAGE
# ==================================================

def test_both_classes_in_every_split(datasets):
    for name, df in datasets.items():
        counts = df[TARGET].value_counts()

        assert counts.get(0, 0) > 0, (
            f"{name}: no BENIGN records"
        )

        assert counts.get(1, 0) > 0, (
            f"{name}: no ATTACK records"
        )


# ==================================================
# TEST 12 — SPLIT PROPORTIONS
# ==================================================

def test_split_proportions(datasets):
    """
    Notebook 10 uses approximate 70/15/15
    hash-based splitting.

    The tolerance accounts for unevenly sized
    groups of identical feature signatures.
    """

    total = sum(len(df) for df in datasets.values())

    expected = {
        "train": 0.70,
        "validation": 0.15,
        "test": 0.15,
    }

    for name, target_ratio in expected.items():
        actual_ratio = len(datasets[name]) / total

        assert abs(actual_ratio - target_ratio) < 0.05, (
            f"{name}: unexpected split proportion "
            f"{actual_ratio:.4%}"
        )


# ==================================================
# TEST 13 — METADATA COMPLETENESS
# ==================================================

def test_metadata_integrity(datasets):
    for name, df in datasets.items():
        assert not df[METADATA].isna().any().any(), (
            f"{name}: missing metadata"
        )

        assert (
            df["SourceRow"] >= 0
        ).all(), f"{name}: negative source rows"

        assert df["Label"].astype(str).str.strip().ne(
            ""
        ).all(), f"{name}: empty original labels"


# ==================================================
# TEST 14 — FEATURE ORDER
# ==================================================

def test_feature_order_consistency(datasets):
    """
    Feature order must stay identical across all
    partitions for consistent model inference.
    """

    reference = list(datasets["train"][FEATURES].columns)

    for name in SPLITS:
        actual = list(datasets[name][FEATURES].columns)

        assert actual == reference, (
            f"{name}: inconsistent feature order"
        )
